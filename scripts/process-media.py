#!/usr/bin/env python3
"""
Builds the gallery from the client's original media.

  python3 scripts/process-media.py <path-to-zip-or-folder>

Reads  scripts/gallery-source.json  (the curation source of truth: category, titles EN/BN, held-back files).
Writes
  public/media/images/img-NNN.webp   full-resolution WebP (original pixel dimensions, q=86)
  public/media/thumbs/img-NNN.webp   480px-wide WebP thumbnails (q=80)
  data/gallery/assets.generated.ts   dimensions, paths, tiny blur placeholders
  data/gallery/manifest.ts           id -> category / featured / review flag
  data/en/media-items.ts, data/bn/media-items.ts   localized titles + alt text
  scripts/MEDIA_REPORT.md            what was published, held back, duplicated, or unusable

Files listed under "hold" are NEVER copied into public/ (privacy / sign-off). Move an id from "hold" to "items"
(with category + titles) and re-run to publish it. Requires Pillow.
"""
import base64, hashlib, io, json, os, shutil, sys, tempfile, zipfile
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = json.loads((ROOT / "scripts" / "gallery-source.json").read_text(encoding="utf-8"))
CAT_LABELS_ALT = {  # used to build alt text
    "en": {"healthcare": "healthcare and welfare", "environment": "environment", "infrastructure": "infrastructure and safety",
           "education": "education, youth and culture", "economy": "economy and livelihood", "voice": "public voice",
           "events": "event", "portraits": "portrait"},
    "bn": {"healthcare": "স্বাস্থ্য ও কল্যাণ", "environment": "পরিবেশ", "infrastructure": "অবকাঠামো ও নিরাপত্তা",
           "education": "শিক্ষা, যুব ও সংস্কৃতি", "economy": "অর্থনীতি ও জীবিকা", "voice": "জনকণ্ঠ",
           "events": "অনুষ্ঠান", "portraits": "প্রতিকৃতি"},
}
KIND = {"portraits": "photo", "events": "photo"}  # everything else is a campaign poster

def load_files(arg: str):
    p = Path(arg)
    tmp = None
    if p.is_file() and p.suffix.lower() == ".zip":
        tmp = tempfile.mkdtemp()
        with zipfile.ZipFile(p) as z:
            z.extractall(tmp)
        p = Path(tmp)
    files = sorted(f for f in os.listdir(p) if not f.startswith("."))
    return p, files, tmp

def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    folder, files, tmp = load_files(sys.argv[1])
    report = {"unusable": [], "duplicates": [], "published": [], "held": [], "warnings": []}

    # --- integrity + duplicates (by byte hash) ---
    seen, dup_of = {}, {}
    for idx, f in enumerate(files):
        raw = (folder / f).read_bytes()
        try:
            im = Image.open(io.BytesIO(raw)); im.verify()
        except Exception as e:
            report["unusable"].append((idx, f, str(e)))
            continue
        h = hashlib.md5(raw).hexdigest()
        if h in seen:
            dup_of[idx] = seen[h]; report["duplicates"].append((idx, f, seen[h], files[seen[h]]))
        else:
            seen[h] = idx

    out_full = ROOT / "public" / "media" / "images"
    out_thumb = ROOT / "public" / "media" / "thumbs"
    for d in (out_full, out_thumb):
        if d.exists(): shutil.rmtree(d)
        d.mkdir(parents=True)

    items, generated = SRC["items"], {}
    for key in sorted(items):
        idx = int(key)
        if idx >= len(files): report["warnings"].append(f"{key}: index beyond file list"); continue
        if idx in dup_of:
            report["warnings"].append(f"{key}: duplicate of {dup_of[idx]:03d}; not published twice"); items = {k: v for k, v in items.items() if k != key}; continue
        if any(u[0] == idx for u in report["unusable"]): continue
        im = ImageOps.exif_transpose(Image.open(folder / files[idx])).convert("RGB")
        w, h = im.size
        id_ = f"img-{key}"
        im.save(out_full / f"{id_}.webp", "WEBP", quality=86, method=6)
        th = im.copy(); th.thumbnail((480, 10000), Image.LANCZOS)
        th.save(out_thumb / f"{id_}.webp", "WEBP", quality=80, method=6)
        b = im.copy(); b.thumbnail((14, 14 * 4), Image.LANCZOS)
        buf = io.BytesIO(); b.save(buf, "JPEG", quality=45)
        blur = "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()
        generated[id_] = dict(src=f"/media/images/{id_}.webp", thumb=f"/media/thumbs/{id_}.webp", width=w, height=h, blur=blur, source=files[idx])
        report["published"].append((id_, files[idx], w, h))

    for key, why in SRC["hold"].items():
        report["held"].append((f"img-{key}", files[int(key)] if int(key) < len(files) else "?", why))

    # --- generated TS ---
    ids = sorted(generated)
    gen = ["// GENERATED by scripts/process-media.py — do not edit by hand.", "export const generatedImages = {"]
    for i in ids:
        g = generated[i]
        gen.append(f'  "{i}": {{ src: "{g["src"]}", thumb: "{g["thumb"]}", width: {g["width"]}, height: {g["height"]}, blur: "{g["blur"]}", source: {json.dumps(g["source"], ensure_ascii=False)} }},')
    gen += ["} as const;", "", "export type GeneratedImageId = keyof typeof generatedImages;", ""]
    (ROOT / "data/gallery").mkdir(parents=True, exist_ok=True)
    (ROOT / "data/gallery/assets.generated.ts").write_text("\n".join(gen), encoding="utf-8")

    man = ['// GENERATED from scripts/gallery-source.json by scripts/process-media.py.',
           '// `review` is an internal sign-off note and is never shown to visitors.',
           'import type { GalleryCategory } from "@/types/gallery";',
           'import type { GeneratedImageId } from "./assets.generated";', '',
           'export interface ManifestEntry { id: GeneratedImageId; category: GalleryCategory; featured?: boolean; review?: string }', '',
           'export const galleryManifest: ManifestEntry[] = [']
    for i in ids:
        it = items[i.split("-")[1]]
        extra = (", featured: true" if it.get("featured") else "") + (f', review: {json.dumps(it["review"], ensure_ascii=False)}' if it.get("review") else "")
        man.append(f'  {{ id: "{i}", category: "{it["category"]}"{extra} }},')
    man += ["];", ""]
    (ROOT / "data/gallery/manifest.ts").write_text("\n".join(man), encoding="utf-8")

    for lang in ("en", "bn"):
        t = [f'// GENERATED from scripts/gallery-source.json by scripts/process-media.py ({lang}).',
             'import type { GalleryItemText } from "@/types/gallery";', '',
             f'export const mediaItems{lang.capitalize()}: Record<string, GalleryItemText> = {{']
        for i in ids:
            it = items[i.split("-")[1]]
            title = it[lang]
            kind = KIND.get(it["category"], "poster")
            if lang == "en":
                alt = f'{title} — {"photo" if kind == "photo" else "campaign poster"}' if it["category"] != "portraits" else title
            else:
                alt = f'{title} — {"ছবি" if kind == "photo" else "প্রচারণা পোস্টার"}' if it["category"] != "portraits" else title
            t.append(f'  "{i}": {{ title: {json.dumps(title, ensure_ascii=False)}, alt: {json.dumps(alt, ensure_ascii=False)} }},')
        t += ["};", ""]
        (ROOT / f"data/{lang}/media-items.ts").write_text("\n".join(t), encoding="utf-8")

    # --- report ---
    full_kb = sum(p.stat().st_size for p in out_full.glob("*.webp")) / 1024
    th_kb = sum(p.stat().st_size for p in out_thumb.glob("*.webp")) / 1024
    src_kb = sum((folder / f).stat().st_size for f in files) / 1024
    lines = ["# Media processing report", "",
             f"Source files: **{len(files)}** · unusable/corrupt: **{len(report['unusable'])}** · exact duplicates: **{len(report['duplicates'])}** · "
             f"published: **{len(report['published'])}** · held back: **{len(report['held'])}** · videos found: **0**", "",
             f"Size: originals {src_kb/1024:.1f} MB → published full-size {full_kb/1024:.1f} MB + thumbnails {th_kb/1024:.1f} MB", ""]
    lines += ["## Unusable / corrupt", *( [f"- {f}: {e}" for _, f, e in report["unusable"]] or ["- none"] ), ""]
    lines += ["## Exact duplicates (second copy not published)", *( [f"- `{f}` = `{o}`" for _, f, _, o in report["duplicates"]] or ["- none"] ), ""]
    lines += ["## Held back (NOT copied to public/)", "| id | original file | reason |", "|---|---|---|", *[f"| {i} | {f} | {w} |" for i, f, w in report["held"]], ""]
    lines += ["## Published items flagged for client review", "| id | note |", "|---|---|", *[f"| img-{k} | {v['review']} |" for k, v in sorted(items.items()) if v.get('review')], ""]
    lines += ["## Warnings", *( [f"- {w}" for w in report["warnings"]] or ["- none"] ), ""]
    (ROOT / "scripts/MEDIA_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"published {len(report['published'])}, held {len(report['held'])}, dups {len(report['duplicates'])}, unusable {len(report['unusable'])}")
    print(f"full {full_kb/1024:.1f} MB, thumbs {th_kb/1024:.1f} MB (from {src_kb/1024:.1f} MB)")
    for w in report["warnings"]: print("WARN", w)
    if tmp: shutil.rmtree(tmp)

main()
